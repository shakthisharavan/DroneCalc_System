//  - Plural: a key that takes {count} has forms  key.one  and  key.other  (a language that needs more adds key.few, key.many, key.two, key.zero).
//    English needs one and other; a translation may add forms its language needs but must keep the same placeholders in each form.
//  - {b}...{/b} marks bold text and is the ONLY markup allowed in a value. No HTML, no entities: write & and < as they are, the page escapes them.
